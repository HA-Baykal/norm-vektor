export default async function handler(req: Request): Promise<Response> {
  const url = new URL(req.url);
  const path = url.searchParams.get("path") || url.pathname;

  let html = "";
  try {
    const r = await fetch(new URL("/", url).toString());
    html = await r.text();
  } catch {
    return new Response("Server error", { status: 500 });
  }

  const page = PAGES[path];
  
  // Базовые мета-теги
  const metaTags = `
    <meta name="description" content="${page ? esc(page.description) : 'Вектор Комфорта'}"/>
    <meta property="og:title" content="${page ? esc(page.title) : 'Вектор Комфорта'}"/>
    <meta property="og:description" content="${page ? esc(page.description) : 'Вектор Комфорта'}"/>
    <meta property="og:url" content="https://www.vektor-komforta.ru${path}"/>
    <meta property="og:image" content="https://www.vektor-komforta.ru/images/hero-bg.jpg"/>
    <link rel="canonical" href="https://www.vektor-komforta.ru${path}"/>
  `;

  // SEO-контент для поисковиков (скрытый через CSS, но видимый для роботов)
  const seoContent = page ? `
    <div style="display:none;">
      <h1>${esc(page.h1)}</h1>
      ${page.bodyHtml}
    </div>
  ` : '';

  // Внедряем мета-теги в <head> и SEO-контент в <body>
  html = html
    .replace(/<title>.*?<\/title>/i, `<title>${page ? esc(page.title) : 'Вектор Комфорта'}</title>`)
    .replace(/<meta\s+name="description"[^>]*>/i, "")
    .replace(/<meta\s+property="og:[^"]*"[^>]*>/gi, "")
    .replace(/<link\s+rel="canonical"[^>]*>/i, "")
    .replace("</head>", `${metaTags}</head>`)
    .replace(/<div id="root"><\/div>/i, `<div id="root"></div>${seoContent}`);

  return new Response(html, { headers: { "content-type": "text/html; charset=utf-8" } });
}
