// ---------------------------------------------------------------------------
// Сериализация в HTML — для серверного рендера в api/page.ts.
// ---------------------------------------------------------------------------
function escHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
function linkify(s: string) {
  return escHtml(s).replace(/(https?:\/\/[^\s,;)]+[^\s,;.)])/g, (u) => `<a href="${u}" rel="noopener">${u}</a>`);
}
export function legalDocToHtml(doc: LegalDoc): string {
  return doc.blocks.map((b) => {
    switch (b.type) {
      case "h2": return `<h2>${escHtml(b.text)}</h2>`;
      case "p": return `<p>${linkify(b.text)}</p>`;
      case "ul": return `<ul>${b.items.map((i) => `<li>${linkify(i)}</li>`).join("")}</ul>`;
      case "table": return `<table>${b.rows.map(([k, v]) => `<tr><th>${escHtml(k)}</th><td>${linkify(v)}</td></tr>`).join("")}</table>`;
    }
  }).join("\n") + `\n<p>См. также: ${LEGAL_NAV.filter((l) => l.href !== doc.path).map((l) => `<a href="${l.href}">${l.label}</a>`).join(", ")}, <a href="/kontakty">Контакты</a>.</p>`;
}
